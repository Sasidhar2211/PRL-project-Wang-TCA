"""
Builds a comparison report: paper's reported Table 1 numbers (restricted to the 8
datasets we have) vs. our reproduction with the original code vs. our gap-proposal
pruning schedules. Reads results_original.csv and results_gap_experiment.csv (written
incrementally by scripts/run_full_comparison.sh) and writes comparison_report.md.

Run from the TCA repo root: python scripts/compare_results.py
"""
import csv
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# CLI dataset key -> (display name used in the paper's Table 1)
DATASET_NAMES = {
    "fgvc": "Aircraft",
    "caltech101": "Caltech101",
    "dtd": "DTD",
    "eurosat": "EuroSAT",
    "oxford_flowers": "Flower102",
    "food101": "Food101",
    "oxford_pets": "Pets",
    "ucf101": "UCF101",
}
DS_ORDER = ["fgvc", "caltech101", "dtd", "eurosat", "oxford_flowers", "food101", "oxford_pets", "ucf101"]

# Paper's own Table 1 numbers (Wang et al., ICCV 2025), restricted to our 8 available
# datasets (Stanford Cars and SUN397 excluded - see PROJECT_STATUS.md for why). The
# paper's official "Average" column is over all 10 datasets, so it will NOT match the
# "8-dataset avg" computed here - both are shown below, clearly labeled.
